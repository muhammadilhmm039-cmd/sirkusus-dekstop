    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
       if (!validasiInput()) {
    return;
}

String nama = txtNama.getText().trim();
String jenis = getJenisPeserta();
String kursus = cmbKursus.getSelectedItem().toString();

double biayaDasar = hitungBiayaDasar(kursus);

double diskon = jenis.equals("Mahasiswa")
        ? biayaDasar * 0.10 : 0;

double biayaFasilitas = hitungBiayaFasilitas();

double total = biayaDasar - diskon + biayaFasilitas;

String fasilitas = buatRingkasanFasilitas();

String ringkasan =
        "PENDAFTARAN KURSUS\n" +
        "==============================\n" +
        "Nama            : " + nama + "\n" +
        "Jenis Peserta   : " + jenis + "\n" +
        "Kursus          : " + kursus + "\n" +
        "Biaya Dasar     : Rp" + String.format("%,.0f", biayaDasar) + "\n" +
        "Diskon          : Rp" + String.format("%,.0f", diskon) + "\n" +
        "Fasilitas:\n" + fasilitas +
        "Biaya Fasilitas : Rp" + String.format("%,.0f", biayaFasilitas) + "\n" +
        "==============================\n" +
        "TOTAL            : Rp" + String.format("%,.0f", total);

txtRingkasan.setText(ringkasan);

String nim = txtNim.getText().trim();
String namaPeserta = txtNama.getText().trim();
String jenisKelamin = "";

if (rbMahasiswa.isSelected()) {
    jenisKelamin = "L";
} else if (rbUmum.isSelected()) {
    jenisKelamin = "P";
}

String prodi = txtProdi.getText().trim();
String noHp = txtNoHp.getText().trim();
String email = txtEmail.getText().trim();

String sql = "INSERT INTO peserta "
        + "(nim, nama, jenis_kelamin, prodi, no_hp, email) "
        + "VALUES (?, ?, ?, ?, ?, ?)";

try (Connection conn = Database.getConnection();
     PreparedStatement ps = conn.prepareStatement(sql)) {

    ps.setString(1, nim);
    ps.setString(2, namaPeserta);
    ps.setString(3, jenisKelamin);
    ps.setString(4, prodi);
    ps.setString(5, noHp);
    ps.setString(6, email);

    ps.executeUpdate();

    JOptionPane.showMessageDialog(
            this,
            "Data peserta berhasil disimpan ke database!",
            "Berhasil",
            JOptionPane.INFORMATION_MESSAGE
    );

} catch (SQLException ex) {
    JOptionPane.showMessageDialog(
            this,
            "Gagal menyimpan data peserta: " + ex.getMessage(),
            "Kesalahan Database",
            JOptionPane.ERROR_MESSAGE
    );
    ex.printStackTrace();
    return;
}

JOptionPane.showMessageDialog(
        this,
        "Pendaftaran berhasil diproses.",
        "Berhasil",
        JOptionPane.INFORMATION_MESSAGE
);
    }//GEN-LAST:event_btnProsesActionPerformed

